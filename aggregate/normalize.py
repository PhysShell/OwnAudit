#!/usr/bin/env python3
"""
Normalization: every tool's SARIF -> one categorized findings set.

This is the stage that turns four analyzers' SARIF logs into the
`findings.json` the rest of OwnAudit reads (`report/`, `viz/`, `runtime/`,
`fix/`). It was ported here from the deprecated `Own.NET/audit/aggregate/`
(issue Own.NET#266, slice 1A): OwnAudit is the canonical audit repo, and until
now the pipeline reached across into a neighbouring Own.NET worktree to run the
normalizer - `Run-Audit.ps1` literally invoked `python $Worktree\\audit\\aggregate
\\normalize.py`. Production no longer imports or executes Python from another
checkout.

Three honesty rules, unchanged from the reference implementation:

  * Unmapped rules are **not dropped** - they land in ``uncategorized`` and are
    surfaced in coverage, so the taxonomy grows deliberately.
  * ``OWN001`` is an umbrella leak code; it is split by its ``[resource: ...]``
    tag so subscription/timer leaks (cat. 2/3) are not collapsed into the
    IDisposable bucket (cat. 1).
  * Third-party (DevExpress) findings are baseline-suppressed - dropped from the
    main report but **counted** in coverage, never hidden silently.

WHAT CHANGED IN THE PORT, AND WHY EACH CHANGE IS SAFE
-----------------------------------------------------
The output is byte-identical for the same inputs; `tests/test_normalize.py`
holds a payload generated by the reference implementation and diffs against it.
Only the two seams moved:

  * the SARIF reader is `aggregate/sarif_read.py` (vendored) instead of
    `scripts/oracle_compare.py` reached through a `sys.path.insert` two
    directories up;
  * the taxonomy is JSON instead of YAML, because OwnAudit's Python tooling is
    stdlib-only and CI installs no packages. The mapping is a mechanical
    transcription; the YAML comments live in the file's `_doc` block, and the
    transcription is re-verifiable against the reference file (`OWNNET_REF`).

Nothing about the taxonomy, the suppression rule or the coverage ledger was
"improved" on the way - a port that also changes semantics cannot be checked by
a parity fixture, and the parity fixture is the only reason to believe the port.

Usage:
  normalize.py --sarif own-check=own.sarif --sarif codeql=codeql.sarif \\
               [--taxonomy aggregate/taxonomy/categories.json] \\
               [--strip PREFIX] [--json out.json]
  normalize.py --selftest
"""

