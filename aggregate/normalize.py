RESOURCE_RE = re.compile(r"\[resource:\s*([^\]]+)\]", re.IGNORECASE)

#: The shipped knowledge base. Colocated with its only reader.
DEFAULT_TAXONOMY = Path(__file__).resolve().parent / "taxonomy" / "categories.json"

#: The payload contract. `normalized-findings/v1` is the retroactive name for the
#: unversioned ten-field shape that slice 1A froze; v2 adds identity and
#: provenance ON TOP of it, changing none of those ten fields. A consumer that
#: only knows v1 can still read a v2 record - `aggregate/tests/test_normalize.py`
#: proves that by projecting v2 back down and diffing it against the v1 golden
#: byte for byte.
SCHEMA_VERSION = "normalized-findings/v2"

#: The ten fields slice 1A froze, in order. Kept as data so the projection test
#: and `finding_to_dict` cannot drift apart.
V1_FIELDS = ("tool", "path", "line", "rule", "category", "category_name",
             "resource", "suppressed", "suppress_reason", "message")


@dataclass
class AuditFinding:
    """One analyzer result, categorized. ``fkey`` is the basename (lower-cased) for
    cross-tool matching - robust to the path-prefix differences between tools (one
    reports ``src/Broker/X.cs``, another ``Broker/X.cs``, a third an absolute path)."""

    tool: str
    path: str
    line: int
    rule: str
    message: str
    category: int = 0
    category_name: str = "uncategorized"
    resource: str | None = None
    suppressed: bool = False
    suppress_reason: str = ""
    note: bool = False           # analysis-skipped coverage note (e.g. OWN050), not a verdict
    #: `region.startColumn`, or None when the producer did not report one. Feeds
    #: the physical anchor; deliberately NOT one of the ten emitted v1 fields.
    column: int | None = None
    fkey: str = field(init=False, default="")

    def __post_init__(self) -> None:
        self.fkey = self.path.lower().rsplit("/", 1)[-1]

    @property
    def module(self) -> str:
        """Directory of the finding (the heatmap roll-up unit), or ``(root)``."""
        return self.path.rsplit("/", 1)[0] if "/" in self.path else "(root)"

    @property
    def scored(self) -> bool:
        """A finding counts toward the report only if it is neither third-party
        suppressed nor an analysis-skipped coverage note."""
        return not self.suppressed and not self.note


@dataclass
class Taxonomy:
    rules: dict[str, Any]
    category_severity: dict[int, str]
    suppress_tokens: list[str]
    coverage_note_rules: set[str]

    def severity_for(self, category: int) -> str:
        return self.category_severity.get(category, "P3")


class TaxonomyError(ValueError):
    """The taxonomy file is malformed. Raised instead of mis-categorizing."""


def load_taxonomy(path: str | Path | None = None) -> Taxonomy:
    """Read `categories.json`.

    Keys beginning with `_` are documentation, not data: JSON has no comments, so
    the rationale that lived in the YAML's comments rides along in `_doc` and is
    skipped here. A rule whose spec is not an object is an error rather than a
    later `AttributeError` deep inside matching - a taxonomy typo must fail loudly,
    since the alternative is a whole category quietly reading as `uncategorized`.
    """
    data = json.loads(Path(path or DEFAULT_TAXONOMY).read_text(encoding="utf-8")) or {}
    rules: dict[str, Any] = {}
    for pat, spec in (data.get("rules") or {}).items():
        if pat.startswith("_"):
            continue
        if not isinstance(spec, dict):
            raise TaxonomyError(f"taxonomy rule {pat!r}: expected an object, got {type(spec).__name__}")
        rules[pat] = spec
    sev = {int(k): str(v) for k, v in (data.get("category_severity") or {}).items()
           if not str(k).startswith("_")}
    suppress = list((data.get("suppress") or {}).get("path_or_message_contains") or [])
    notes = {str(r) for r in (data.get("coverage_notes") or [])}
    return Taxonomy(rules=rules, category_severity=sev, suppress_tokens=suppress,
                    coverage_note_rules=notes)


def _resource_tag(message: str) -> str | None:
    m = RESOURCE_RE.search(message or "")
    return m.group(1).strip().lower() if m else None


def _match_rule(rule: str, rules: dict[str, Any]) -> dict[str, Any] | None:
    """Resolve a ruleId to its taxonomy spec. Exact match wins; otherwise the most
    specific glob (longest non-wildcard run) wins."""
    if rule in rules:
        return rules[rule]
    best: tuple[int, dict[str, Any]] | None = None
    for pat, spec in rules.items():
        if any(c in pat for c in "*?[") and fnmatchcase(rule, pat):
            specificity = len(pat.replace("*", "").replace("?", ""))
            if best is None or specificity > best[0]:
                best = (specificity, spec)
    return best[1] if best else None


def categorize(rule: str, resource: str | None,
               rules: dict[str, Any]) -> tuple[int, str]:
    """(category, name) for a ruleId, splitting umbrella codes by resource tag."""
    spec = _match_rule(rule, rules)
    if spec is None:
        return 0, "uncategorized"
    if "by_resource" in spec:
        by = spec["by_resource"]
        chosen = by.get(resource) if resource is not None else None
        if chosen is None:
            chosen = by.get("*", {})
        return int(chosen.get("category", 0)), str(chosen.get("name", "uncategorized"))
    return int(spec.get("category", 0)), str(spec.get("name", "uncategorized"))


def _suppressed(path: str, message: str, tokens: list[str]) -> str:
    """Reason string if this finding is third-party baseline-suppressed, else ''."""
    hay = f"{path}\n{message}".lower()
    for tok in tokens:
        if tok.lower() in hay:
            return f"third-party: {tok}"
    return ""


def normalize_results(raw: list[Any], tax: Taxonomy) -> list[AuditFinding]:
    """Turn RawFindings (tool/path/line/rule/message) into categorized AuditFindings."""
    out: list[AuditFinding] = []
    for f in raw:
        resource = _resource_tag(f.message)
        category, name = categorize(f.rule, resource, tax.rules)
        reason = _suppressed(f.path, f.message, tax.suppress_tokens)
        is_note = f.rule in tax.coverage_note_rules
        out.append(AuditFinding(
            tool=f.tool, path=f.path, line=f.line, rule=f.rule, message=f.message,
            category=category, category_name=name, resource=resource,
            suppressed=bool(reason), suppress_reason=reason, note=is_note,
            column=getattr(f, "column", None)))
    return out


def coverage(findings: list[AuditFinding],
             reads: dict[str, SarifReadResult]) -> dict[str, Any]:
    """The honesty ledger: what was categorized, what was suppressed, which rules
    are analysis-skipped coverage notes, and which rules have no taxonomy entry yet
    (so they are visibly pending, not lost).

    `total` keeps the meaning it has always had - results that could be
    normalized - and does NOT grow to include locationless ones. They are not
    findings; they are results that could not become findings, and the ledger
    states them separately so the two together reconcile against the raw SARIF:

        total + no_physical_location == sum(len(run.results))

    `reads` is required rather than optional. Defaulting it would let a caller
    that never measured the loss emit `no_physical_location: 0`, which reads
    downstream as "measured, none found" - the report-health-you-never-measured
    failure this ledger exists to prevent.
    """
    kept = [f for f in findings if f.scored]
    suppressed = [f for f in findings if f.suppressed]
    notes = [f for f in findings if f.note and not f.suppressed]
    uncategorized = Counter(f.rule for f in kept if f.category == 0)
    lost_by = {tool: dict(r.no_physical_location_by_rule)
               for tool, r in sorted(reads.items()) if r.no_physical_location}
    return {
        "tools": sorted({f.tool for f in findings}),
        "total": len(findings),
        "kept": len(kept),
        "suppressed": len(suppressed),
        "suppressed_by": dict(Counter(f.suppress_reason for f in suppressed)),
        "analysis_skipped": len(notes),
        "analysis_skipped_by": dict(Counter(f.rule for f in notes)),
        "by_category": dict(Counter(f.category for f in kept)),
        "uncategorized_rules": dict(uncategorized),
        #: Results the producers emitted that carry no usable physical location,
        #: so they could not be anchored into findings (#57). Reported, never
        #: silently dropped; see `aggregate/sarif_read.py` for why they are not
        #: admitted with a fabricated `path`/`line`.
        "no_physical_location": sum(r.no_physical_location for r in reads.values()),
        "no_physical_location_by": lost_by,
    }


def normalize(sarif_inputs: list[tuple[str, str]], tax: Taxonomy, strips: list[str],
              ) -> tuple[list[AuditFinding], dict[str, Any], dict[str, str | None]]:
    """Findings, coverage, and each producer's self-declared driver version.

    The version rides along from the same parse rather than costing a second read
    of a 35 MB file - and it is *observed*, not asserted: only CodeQL declares one
    in the recorded corpus.

    Producer names must be unique HERE, not only in `build_payload`. `reads` is
    keyed by producer, so a duplicate name silently keeps both inputs' findings
    while retaining only the last input's locationless count - the two then no
    longer reconcile, which is precisely the accounting #57 exists to make
    trustworthy. Before this function counted anything the collision cost a
    nullable version string and was harmless; it is not harmless now.
    """
    prov.check_unique_producers(sarif_inputs)
    raw: list[Any] = []
    versions: dict[str, str | None] = {}
    reads: dict[str, SarifReadResult] = {}
    for tool, path in sarif_inputs:
        read = read_sarif(Path(path).read_text(encoding="utf-8"), tool, strips)
        raw += read.findings
        versions[tool] = read.driver_version
        reads[tool] = read
    findings = normalize_results(raw, tax)
    return findings, coverage(findings, reads), versions


def finding_to_dict(f: AuditFinding) -> dict[str, Any]:
    """The ten fields slice 1A froze, in their frozen order. Do not extend this -
    identity and provenance are added by `attach_identity`, on top and after."""
    return {
        "tool": f.tool, "path": f.path, "line": f.line, "rule": f.rule,
        "category": f.category, "category_name": f.category_name,
        "resource": f.resource, "suppressed": f.suppressed,
        "suppress_reason": f.suppress_reason, "message": f.message,
    }


